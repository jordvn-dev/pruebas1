USE RPG
DECLARE @DESCUBRIR_HACKER AS INT
SET @DESCUBRIR_HACKER = (SELECT TOP 1 ID FROM JUGADORES WHERE MONEDAS > 9000)
SELECT * FROM JUGADORES
WHERE ID = @DESCUBRIR_HACKER

INSERT INTO BANEADOS (ID,NOMBRE, NIVEL, MONEDAS, CLASE)
SELECT ID, NOMBRE, NIVEL, MONEDAS, CLASEFROM JUGADORES
WHERE ID = @DESCUBRIR_HACKER

DELETE FROM JUGADORES WHERE ID = @DESCUBRIR_HACKER