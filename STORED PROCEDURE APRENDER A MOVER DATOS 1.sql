CREATE PROC SP_ELIMINAR_BAN
	@ID_JUGADOR INT
AS
	INSERT INTO JUGADORES
	SELECT NOMBRE, NIVEL, MONEDAS, CLASE FROM BANEADOS WHERE ID = @ID_JUGADOR

	DELETE FROM BANEADOS WHERE ID = @ID_JUGADOR

EXEC SP_ELIMINAR_BAN 16 --AL PONER @ID_JUGADOR CREAMOS UNA "VARIABLE" LA CUAL NOS SIRVE AL MOMENTO DE EJECUTAR, COMO VEMOS LUEGO DEL EXEC SP_ELIMINAR_BAN PONEMOS "16, ESE 16 SE GUARDARA EN LA VARIABLE @ID_JUGADOR, PARA ASI EJECUTAR EL CODIGO Y BANEAR AL JUGADOR CON ESA ID"

EXEC SP_BANEAR








