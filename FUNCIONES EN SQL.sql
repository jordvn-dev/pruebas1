create function PROMEDIO_MONEDAS()
RETURNS INT
AS
BEGIN
	DECLARE @CANTIDAD_JUGADORES INT;
	DECLARE @CANTIDAD_MONEDAS INT;

	SET @CANTIDAD_JUGADORES =(SELECT COUNT(NOMBRE) FROM JUGADORES)
	SET @CANTIDAD_MONEDAS = (SELECT SUM(MONEDAS) FROM JUGADORES)

	IF @CANTIDAD_JUGADORES = 0
		RETURN 0
	RETURN @CANTIDAD_MONEDAS / @CANTIDAD_JUGADORES

END
GO

