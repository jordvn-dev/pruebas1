--DIFERENCIA ENTRE JOINS--

SELECT * FROM EMPLEADOS_HX EHX LEFT JOIN HORAS_EXTRA HX ON HX.ID_EMPLEADO = EHX.ID_EMPLEADO

--LEFT JOIN MUESTRA TODOS LOS CAMPOS AUNQUE ESTEN VACIOS "NULLS"--

SELECT * FROM HORAS_EXTRA HX INNER JOIN EMPLEADOS_HX EHX ON HX.ID_EMPLEADO = EHX.ID_EMPLEADO

--INNER JOIN MUESTRA TODOS LOS CAMPOS QUE ESTEN 100% EN LAS DOS TABLAS--

SELECT * FROM EMPLEADOS_HX EHX RIGHT JOIN HORAS_EXTRA HX ON HX.ID_EMPLEADO = EHX.ID_EMPLEADO

SELECT * FROM HORAS_EXTRA HX RIGHT JOIN EMPLEADOS_HX EHX ON HX.ID_EMPLEADO = EHX.ID_EMPLEADO

