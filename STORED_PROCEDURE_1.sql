CREATE PROC SP_BUSCARREGISTRO_STATUS
@PRO_CODIGO INT
AS
BEGIN
SELECT * FROM PRODUCTO WHERE PRO_CODIGO = @PRO_CODIGO
END

GO

CREATE PROC SP_CHECKLOGIN @USUARIO VARCHAR(50)='', @CLAVE VARCHAR(25) =''
AS
BEGIN
IF EXISTS(SELECT LOG_CODIGO, LOG_USUARIO, LOG_DEPARTAMENTO,LOG_STATUS,LOG_CARGO,LOG_NOMBRE,LOG_APELLIDO FROM LOGIN WHERE LOG_USUARIO = @USUARIO AND LOG_CLAVE = @CLAVE)
BEGIN
SELECT LOG_CODIGO, LOG_USUARIO, LOG_DEPARTAMENTO, LOG_STATUS, LOG_CARGO, LOG_NOMBRE, LOG_APELLIDO FROM LOGIN WHERE LOG_USUARIO = @USUARIO;
END
END