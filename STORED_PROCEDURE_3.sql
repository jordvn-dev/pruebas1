USE FACTURACION
GO

CREATE PROC SP_CONSULTA_DDLCLIENTE
AS
SELECT TIP_DESCRIPCION FROM TIPOSCLIENTES
GO

CREATE PROC SP_CONSULTA_DDLCOLOR
AS
SELECT COL_DESCRIPCION FROM COLOR
ORDER BY COL_DESCRIPCION
GO

CREATE PROC SP_CONSULTA_DDLMARCA
AS
SELECT MAR_DESCRIPCION FROM MARCA
ORDER BY MAR_DESCRIPCION
GO

CREATE PROC SP_CONSULTA_DDLMEDIDAS
AS
SELECT MED_DESCRIPCION FROM MEDIDAS
ORDER BY MED_CODIGO
GO

CREATE PROC SP_CONSULTA_DDLMODELO
AS
SELECT MOD_DESCRIPCION FROM MODELO
ORDER BY MOD_DESCRIPCION
GO

CREATE PROC SP_CONSULTA_DDLSUBCATEGORIA
AS
SELECT SUB_DESCRIPCION FROM SUBCATEGORIA
ORDER BY SUB_CODIGO
GO

CREATE PROC SP_CONSULTA_DDLUBICACION
AS
SELECT UBI_DESCRIPCION FROM UBICACION
ORDER BY UBI_CODIGO
GO

CREATE PROC SP_CONSULTA_GRIDBODEGA
AS
SELECT BOD_CODIGO, BOD_REFERENCIA, BOD_DESCRIPCION FROM BODEGAS
ORDER BY BOD_CODIGO
GO

CREATE PROC S_CONSULTA_GRIDCAJA
AS
SELECT CAJ_CODIGO, CAJ_REFERENCIA, CAJ_DESCRIPCION FROM CAJA
ORDER BY CAJ_CODIGO
GO

CREATE PROC SP_CONSULTA_GRIDCLIENTE
AS
SELECT CLI_CODIGO,CLI_TIPO,CLI_NOMBRE,CLI_RNC,CLI_CONTACTO,CLI_CARGO,CLI_PAGINA,CLI_APELLIDO,CLI_CEDULA,CLI_DIRECCION,CLI_TELEFONO, CLI_CELULAR, CLI_CORREO, CLI_PAIS, CLI_PROVINCIA FROM CLIENTES
ORDER BY CLI_CODIGO
GO

CREATE PROC SP_CONSULTA_GRIDPRODUCTO
AS
SELECT PRO_CODIGO, PRO_NOMBRE, PRO_FECHA_COMPRA, PRO_PrecioCompraRD,PRO_PrecioCompraUS,PRO_BODEGA, PRO_UBICACION, PRO_STATUS, PRO_APLICARITBIS, PRO_FISICO, PRO_SERVICIO,PRO_OCASIONAL,PRO_CANTIDADINICIAL, PRO_CANTIDADMINIMA, PRO_FECHAEXPIRACION, PRO_SUPLIDOR, PRO_MARCA, PRO_MODELO, PRO_SERIE,PRO_COLOR, PRO_CATEGORIA, PRO_SUBCATEGORIA, PRO_REFERENCIA,PRO_VENDEPOR,PRO_CONTIENEVENDE, PRO_COMPRAPOR,  PRO_CONTIENECOMPRA, PRO_NOTA FROM PRODUCTO
ORDER BY PRO_CODIGO
GO

CREATE PROC SP_CONSULTAPAIS
	(@ID_PAIS INT)
AS
BEGIN
SELECT PAI_NOMBRE FROM PAIS WHERE ID_PAIS = @ID_PAIS
END
GO

CREATE PROC SP_CONSULTAPROVINCIA
(@ID_PROVINCIA INT)
AS
BEGIN
SELECT PRO_NOMBRE FROM PROVINCIA WHERE ID_PAIS = @ID_PROVINCIA
END
GO

